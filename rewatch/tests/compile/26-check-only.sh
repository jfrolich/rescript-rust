#!/bin/bash
set -eu
cd "$(dirname "$0")"
source ../utils.sh

bold "Test: check-only checks without writing, including after a normal build"
work=$(mktemp -d)
trap 'rm -r "$work"' EXIT
# Include ignored build artifacts, directories and symlinks, not just tracked files.
snapshot() {
  node - "$1" <<'JS'
const fs = require('fs'), path = require('path'), crypto = require('crypto');
const root = process.argv[2];
function visit(rel) {
  const file = path.join(root, rel), stat = fs.lstatSync(file);
  if (stat.isSymbolicLink()) console.log(JSON.stringify([rel, 'link', fs.readlinkSync(file)]));
  else if (stat.isDirectory()) {
    console.log(JSON.stringify([rel, 'dir']));
    for (const name of fs.readdirSync(file).sort()) visit(path.join(rel, name));
  } else console.log(JSON.stringify([rel, crypto.createHash('sha256').update(fs.readFileSync(file)).digest('hex')]));
}
visit('');
JS
}
check_unchanged() {
  snapshot "$1" > "$work/before"
  timeout 10 "$REWATCH_EXECUTABLE" build "$1" --check-only > "$work/out" 2> "$work/err"
  snapshot "$1" > "$work/after"
  diff -u "$work/before" "$work/after"
}
repo=../../testrepo
[ -z "$(git status --porcelain -- "$repo")" ]
check_unchanged "$repo"
timeout 10 "$REWATCH_EXECUTABLE" build "$repo" > "$work/out" 2> "$work/err"
check_unchanged "$repo"
[ -z "$(git status --porcelain -- "$repo")" ]

project="$work/project"
mkdir -p "$project/src"
cat > "$project/rescript.json" <<'JSON'
{"name":"check-only-test","sources":"src","package-specs":{"module":"esmodule","in-source":true},"gentypeconfig":{},"warnings":{"number":"+102","error":"-102"}}
JSON
printf 'type t = int\nlet value = 1\n' > "$project/src/A.res"
printf '@genType type t = int\nlet value: int\n' > "$project/src/A.resi"
printf 'let value = A.value + 1\n' > "$project/src/B.res"
check_unchanged "$project"
[ ! -d "$project/lib" ]
timeout 10 "$REWATCH_EXECUTABLE" build "$project" > "$work/out" 2> "$work/err"
check_unchanged "$project"

printf 'let value: int = "wrong"\n' > "$project/src/B.res"
normal_status=0
timeout 10 "$REWATCH_EXECUTABLE" build "$project" > "$work/out" 2> "$work/normal.err" || normal_status=$?
[ "$normal_status" -ne 0 ] && [ "$normal_status" -ne 124 ]
snapshot "$project" > "$work/before"
check_status=0
timeout 10 "$REWATCH_EXECUTABLE" build "$project" --check-only > "$work/out" 2> "$work/check.err" || check_status=$?
[ "$normal_status" -eq "$check_status" ]
diff -u "$work/normal.err" "$work/check.err"
snapshot "$project" > "$work/after"
diff -u "$work/before" "$work/after"

# Warning 102 is generated by Lambda conversion, not typing.
printf 'let compare = (a, b) => a == b\n' > "$project/src/B.res"
timeout 10 "$REWATCH_EXECUTABLE" build "$project" > "$work/out" 2> "$work/normal.err"
grep -q '102' "$work/normal.err"
check_unchanged "$project"
[ ! -s "$work/err" ]
success "Check-only preserves files and typing diagnostics, and omits backend warnings"
