//! What a diagnostic says about code a macro generated.
//!
//! A diagnostic in generated code is reported at the macro use it was
//! generated for: that is the code the person has. After the frame of that
//! use comes a note with the lines of the quote the code was written in,
//! or, for code that is not from a quote, the generated code itself.

use crate::location::Position;
use crate::parser::code_frame;

use super::edit::{GeneratedCode, LineTable, SourceText};

/// The note for a diagnostic in `generated`, a part of the expanded `text`.
/// `read` gives the text of a macro's file.
pub fn generated_code_note(
    text: &SourceText,
    generated: &GeneratedCode,
    warning: bool,
    read: impl Fn(&str) -> String,
) -> String {
    let frame = |text: &str, lines: &LineTable, start: (u32, u32), end: (u32, u32)| {
        let position = |(line, offset): (u32, u32)| {
            let bol = lines.line_start(line).unwrap_or(0);
            Position::new(
                crate::intern::StrIdx::from_raw(0),
                line as i32,
                bol as i32,
                offset as i32,
            )
        };
        let (start, end) = (position(start), position(end));
        if warning {
            code_frame::print_warning(text, &start, &end)
        } else {
            code_frame::print(text, &start, &end)
        }
    };
    let by = match &generated.description {
        Some(description) => format!("generated by {description}"),
        None => "the macro generated".to_string(),
    };
    let mut output = String::new();

    if let Some(quote) = &generated.quote {
        let position = |(line, column): (u32, u32)| {
            Position::new(
                crate::intern::StrIdx::from_raw(0),
                line as i32,
                0,
                column as i32,
            )
        };
        let place =
            code_frame::format_location(&quote.file, &position(quote.start), &position(quote.end));
        output.push_str(&format!("  This is in the code {by}, written at "));
        output.push_str(&code_frame::colorize_location(&place));
        output.push_str("\n\n");
        let source = read(&quote.file);
        let lines = LineTable::new(&source);
        let offset =
            |(line, column): (u32, u32)| lines.line_start(line).map(|start| (line, start + column));
        if let (false, Some(start), Some(end)) =
            (source.is_empty(), offset(quote.start), offset(quote.end))
        {
            output.push_str(&frame(&source, &lines, start, end));
            output.push('\n');
        }
        return output;
    }

    let expanded = text.text();
    let lines = LineTable::new(expanded);
    let place = |offset: u32| (lines.line_of(offset).0 as u32, offset);
    output.push_str(&format!(
        "  This is in the code {by}. In the expanded source:\n\n"
    ));
    output.push_str(&frame(
        expanded,
        &lines,
        place(generated.start),
        place(generated.end),
    ));
    output.push('\n');
    output
}
