//! Imports, exports and the text outside the JavaScript AST.
use super::{
    Unsupported,
    build::{Allocate, Build},
    naming::Names,
};
use crate::js_ir::printer::js_export_name;
use crate::js_ir::{ModuleFormat, ModulePathResolver, arena::JsDepsProgram, op::Kind};
use oxc_allocator::Allocator;
use oxc_ast::ast::*;
use oxc_codegen::Codegen;
use oxc_span::{SPAN, SourceType};
use oxc_syntax::operator::AssignmentOperator;

const HEADER: &str = "// Generated by ReScript, PLEASE EDIT WITH CARE\n";
const EMPTY: &str = "/* This output is empty. Its source's type definitions, externals and/or unused code got optimized away. */\n";

pub(super) fn emit(
    program: &JsDepsProgram,
    resolver: &ModulePathResolver,
    directives: &[String],
    debug: bool,
    _jsx_preserve: bool,
    header: bool,
) -> Result<(String, Option<String>), Unsupported> {
    let p = &program.program;
    let mut text = String::new();
    for directive in directives {
        text.push_str(directive);
        text.push('\n');
    }
    if header {
        text.push_str(HEADER);
    }
    if program.modules.is_empty()
        && program.side_effect.is_none()
        && p.block.is_empty()
        && p.exports.is_empty()
        && p.name_reservations.is_empty()
    {
        text.push_str(EMPTY);
        return Ok((text, None));
    }
    let names = Names::collect(program, resolver)?;
    let allocator = Allocator::default();
    let mut build = Build::new(&allocator, &p.arena, &names);
    build.debug = debug;
    let b = &build.b;
    let mut body = b.vec();
    let commonjs = resolver.module_format() == ModuleFormat::CommonJs;
    let mut ast_directives = b.vec();
    if commonjs {
        ast_directives.push(Directive::new(
            SPAN,
            build.string("use strict"),
            "use strict",
            b,
        ));
    }
    for module in &program.modules {
        if module.dynamic_import {
            continue;
        }
        let Some(path) = resolver.resolve_module_path(module) else {
            continue;
        };
        let name = names.get(&module.id);
        let default = matches!(module.kind, Kind::External { default: true, .. });
        if commonjs {
            let call = Expression::new_call_expression(
                SPAN,
                build.id("require"),
                None,
                b.vec1(Argument::from(build.string_expr(&path))),
                false,
                b,
            );
            body.push(build.variable(
                name,
                Some(if default {
                    build.member(call, "default")
                } else {
                    call
                }),
            ));
        } else {
            if matches!(
                module.kind,
                Kind::External {
                    import_attributes: Some(_),
                    ..
                }
            ) {
                return Err(Unsupported("import attributes"));
            }
            let binding = build.binding(name);
            let specifier = if default {
                ImportDeclarationSpecifier::new_import_default_specifier(SPAN, binding, b)
            } else {
                ImportDeclarationSpecifier::new_import_namespace_specifier(SPAN, binding, b)
            };
            body.push(Statement::new_import_declaration(
                SPAN,
                Some(b.vec1(specifier)),
                build.string(&path),
                None,
                None,
                ImportOrExportKind::Value,
                b,
            ));
        }
    }
    let statements = build.block(&p.block, true)?;
    let no_statements = statements.is_empty();
    body.extend(statements);
    if commonjs {
        for id in &p.exports {
            let export = js_export_name(id.name());
            let target = build.member(build.id("exports"), &export);
            let assignment = Expression::new_assignment_expression(
                SPAN,
                AssignmentOperator::Assign,
                build.target(target)?,
                build.id(names.get(id)),
                b,
            );
            body.push(build.expression_statement(assignment));
            if id.name() == "default" {
                let target = build.member(build.id("exports"), "__esModule");
                let assignment = Expression::new_assignment_expression(
                    SPAN,
                    AssignmentOperator::Assign,
                    build.target(target)?,
                    Expression::new_boolean_literal(SPAN, true, b),
                    b,
                );
                body.push(build.expression_statement(assignment));
            }
        }
    } else if !p.exports.is_empty() {
        let mut specifiers = b.vec();
        for id in &p.exports {
            let local = ModuleExportName::IdentifierName(IdentifierName::new(
                SPAN,
                build.text(names.get(id)),
                b,
            ));
            let exported = ModuleExportName::IdentifierName(IdentifierName::new(
                SPAN,
                build.text(&js_export_name(id.name())),
                b,
            ));
            specifiers.push(ExportSpecifier::new(
                SPAN,
                local,
                exported,
                ImportOrExportKind::Value,
                b,
            ));
        }
        body.push(Statement::new_export_named_declaration(
            SPAN,
            specifiers,
            ImportOrExportKind::Value,
            b,
        ));
    }
    let ast = Program::new(
        SPAN,
        SourceType::mjs(),
        "",
        b.vec(),
        None,
        ast_directives,
        body,
        b,
    );
    let code = Codegen::new().build(&ast).code;
    text.push_str(code.trim_end_matches('\n'));
    // S0's split-file comparison preserves this gap, not just the comment.
    // With no exports the legacy printer ensures two newlines before the trailer.
    text.push_str(if p.exports.is_empty() {
        if no_statements { "\n\n\n" } else { "\n\n" }
    } else {
        "\n"
    });
    match &program.side_effect {
        None => text.push_str("/* No side effect */\n"),
        Some(reason) => {
            text.push_str("/* ");
            text.push_str(reason);
            text.push_str(" Not a pure module */\n");
        }
    }
    Ok((text, None))
}
