//! Imports, exports and the text outside the JavaScript AST.
use super::{
    Unsupported,
    build::{Allocate, Build},
    naming::Names,
};
use crate::js_ir::printer::js_export_name;
use crate::js_ir::{ModuleFormat, ModulePathResolver, arena::JsDepsProgram, op::Kind};
use oxc_allocator::Allocator;
use oxc_ast::ast::*;
use oxc_codegen::{Codegen, CodegenOptions, IndentChar};
use oxc_span::{SPAN, SourceType};
use oxc_syntax::operator::AssignmentOperator;

const HEADER: &str = "// Generated by ReScript, PLEASE EDIT WITH CARE\n";
const EMPTY: &str = "/* This output is empty. Its source's type definitions, externals and/or unused code got optimized away. */\n";

/// Keep these layout options identical to scripts/js-reformat (section E.8).
pub(super) fn codegen_options() -> CodegenOptions {
    CodegenOptions {
        indent_char: IndentChar::Space,
        indent_width: 2,
        ..CodegenOptions::default()
    }
}

pub(super) struct FileOptions {
    pub debug: bool,
    pub jsx_preserve: bool,
    pub header: bool,
}

/// File metadata is borrowed independently of the node representation.
pub(super) struct Unit<'a, V: super::view::View> {
    pub arena: &'a V,
    pub block: &'a [crate::js_ir::arena::Stmt],
    pub exports: &'a [crate::ident::Ident],
    pub reservations: &'a [crate::ident::Ident],
    pub modules: &'a [crate::js_ir::ModuleId],
    pub side_effect: Option<&'a str>,
}

pub(super) fn emit(
    program: &JsDepsProgram,
    resolver: &ModulePathResolver,
    directives: &[String],
    options: FileOptions,
    source_map: Option<&super::sourcemap::Options<'_>>,
    audit: Option<&mut Vec<super::RawSegment>>,
) -> Result<(String, Option<String>), Unsupported> {
    let p = &program.program;
    let names = Names::collect(program, resolver, options.jsx_preserve)?;
    emit_named(
        Unit { arena: &p.arena, block: &p.block, exports: &p.exports,
            reservations: &p.name_reservations, modules: &program.modules,
            side_effect: program.side_effect.as_deref() },
        &names, resolver, directives, options, source_map, audit,
    )
}

pub(super) fn emit_named<V: super::view::View, N: super::view::PrintedNames>(
    unit: Unit<'_, V>,
    names: &N,
    resolver: &ModulePathResolver,
    directives: &[String],
    options: FileOptions,
    source_map: Option<&super::sourcemap::Options<'_>>,
    audit: Option<&mut Vec<super::RawSegment>>,
) -> Result<(String, Option<String>), Unsupported> {
    let FileOptions { debug, jsx_preserve, header } = options;
    let mut text = String::new();
    for directive in directives {
        text.push_str(directive);
        text.push('\n');
    }
    if header {
        text.push_str(HEADER);
    }
    if unit.modules.is_empty()
        && unit.side_effect.is_none()
        && unit.block.is_empty()
        && unit.exports.is_empty()
        && unit.reservations.is_empty()
    {
        text.push_str(EMPTY);
        return Ok(match source_map {
            Some(options) => options.attach(text, options.builder()),
            None => (text, None),
        });
    }
    let allocator = Allocator::default();
    let mut build = Build::new(&allocator, unit.arena, names);
    build.debug = debug;
    build.jsx_preserve = jsx_preserve;
    let spans = source_map.map(|m| super::sourcemap::Spans::new(m.locations.clone(), m.source));
    build.source_map = spans.as_ref();
    let b = &build.b;
    let mut body = b.vec();
    let commonjs = resolver.module_format() == ModuleFormat::CommonJs;
    let mut ast_directives = b.vec();
    if commonjs {
        ast_directives.push(Directive::new(
            SPAN,
            build.string("use strict"),
            "use strict",
            b,
        ));
    }
    for (index, module) in unit.modules.iter().enumerate() {
        if module.dynamic_import {
            continue;
        }
        let Some(path) = resolver.resolve_module_path(module) else {
            continue;
        };
        let name = names.name(unit.arena.name_key(super::view::NameSource::Import(index, module.id)));
        let default = matches!(module.kind, Kind::External { default: true, .. });
        if commonjs {
            let call = Expression::new_call_expression(
                SPAN,
                build.id("require"),
                None,
                b.vec1(Argument::from(build.string_expr(&path))),
                false,
                b,
            );
            body.push(build.variable(
                name,
                Some(if default {
                    build.member(call, "default")
                } else {
                    call
                }),
            ));
        } else {
            // Attributes meet no identifiers and retain source entry order.
            // Legacy quotes every key and value; oxc supplies `with` and braces.
            let attributes = if let Kind::External {
                import_attributes: Some(attributes),
                ..
            } = &module.kind
            {
                let mut entries = b.vec();
                for (key, value) in &attributes.entries {
                    entries.push(ImportAttribute::new(
                        SPAN,
                        ImportAttributeKey::StringLiteral(build.string(key)),
                        build.string(value),
                        b,
                    ));
                }
                Some(WithClause::boxed(SPAN, WithClauseKeyword::With, entries, b))
            } else {
                None
            };
            let binding = build.binding(name);
            let specifier = if default {
                ImportDeclarationSpecifier::new_import_default_specifier(SPAN, binding, b)
            } else {
                ImportDeclarationSpecifier::new_import_namespace_specifier(SPAN, binding, b)
            };
            body.push(Statement::new_import_declaration(
                SPAN,
                Some(b.vec1(specifier)),
                build.string(&path),
                None,
                attributes,
                ImportOrExportKind::Value,
                b,
            ));
        }
    }
    let statements = build.block(unit.block, true)?;
    let no_statements = statements.is_empty();
    body.extend(statements);
    if commonjs {
        for (index, id) in unit.exports.iter().enumerate() {
            let export = js_export_name(id.name());
            let target = build.member(build.id("exports"), &export);
            let assignment = Expression::new_assignment_expression(
                SPAN,
                AssignmentOperator::Assign,
                build.target(target)?,
                build.id(names.name(unit.arena.name_key(super::view::NameSource::Export(index, *id)))),
                b,
            );
            body.push(build.expression_statement(assignment));
            if id.name() == "default" {
                let target = build.member(build.id("exports"), "__esModule");
                let assignment = Expression::new_assignment_expression(
                    SPAN,
                    AssignmentOperator::Assign,
                    build.target(target)?,
                    Expression::new_boolean_literal(SPAN, true, b),
                    b,
                );
                body.push(build.expression_statement(assignment));
            }
        }
    } else if !unit.exports.is_empty() {
        let mut specifiers = b.vec();
        for (index, id) in unit.exports.iter().enumerate() {
            let local = ModuleExportName::IdentifierName(IdentifierName::new(
                SPAN,
                build.text(names.name(unit.arena.name_key(super::view::NameSource::Export(index, *id)))),
                b,
            ));
            let exported = ModuleExportName::IdentifierName(IdentifierName::new(
                SPAN,
                build.text(&js_export_name(id.name())),
                b,
            ));
            specifiers.push(ExportSpecifier::new(
                SPAN,
                local,
                exported,
                ImportOrExportKind::Value,
                b,
            ));
        }
        body.push(Statement::new_export_named_declaration(
            SPAN,
            specifiers,
            ImportOrExportKind::Value,
            b,
        ));
    }
    let source_text = spans.as_ref().map(|s| s.source_text()).unwrap_or_default();
    let ast = Program::new(
        SPAN,
        SourceType::mjs(),
        &source_text,
        b.vec(),
        None,
        ast_directives,
        body,
        b,
    );
    let output = Codegen::new()
        .with_options(CodegenOptions {
            source_map_path: source_map.map(|m| m.source.to_path_buf()),
            ..codegen_options()
        })
        .build(&ast);
    let mut map = source_map.map(|m| m.builder());
    if let (Some(spans), Some(tokens), Some(builder)) = (&spans, &output.map, &mut map) {
        let preamble_lines = text.bytes().filter(|b| *b == b'\n').count();
        for token in tokens.get_tokens() {
            spans.add_token(builder, token.get_src_line(), token.get_src_col(),
                preamble_lines + token.get_dst_line() as usize, token.get_dst_col() as usize);
        }
    }
    let code = output.code;
    let pieces = build.raw_pieces.borrow();
    let mut seen = b.vec();
    seen.resize(pieces.len(), false);
    super::raw::substitute(
        code.trim_end_matches('\n'),
        build.raw_prefix,
        &pieces,
        &mut seen,
        &mut text,
        audit,
    )?;
    // S0's split-file comparison preserves this gap, not just the comment.
    // With no exports the legacy printer ensures two newlines before the trailer.
    text.push_str(if unit.exports.is_empty() {
        if no_statements { "\n\n\n" } else { "\n\n" }
    } else {
        "\n"
    });
    match &unit.side_effect {
        None => text.push_str("/* No side effect */\n"),
        Some(reason) => {
            text.push_str("/* ");
            text.push_str(reason);
            text.push_str(" Not a pure module */\n");
        }
    }
    Ok(match (source_map, map) {
        (Some(options), Some(builder)) => options.attach(text, builder),
        _ => (text, None),
    })
}
