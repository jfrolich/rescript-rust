//! JavaScript IR Printer - Generates JavaScript source code from JS IR.
//!
//! This module provides functionality to convert the JavaScript IR
//! into formatted JavaScript source code.

use super::op::{BinOp, Kind, Number, PropertyName};
use super::{
    Block, CaseClause, Delim, DepsProgram, Expression, ExpressionDesc, ForDirection, JsRawInfo,
    ModulePathResolver, Program, Statement, StatementDesc, StringClause, VIdent,
    VariableDeclaration,
};
use crate::ident::Ident;
use std::collections::HashMap;
use std::fmt::Write;

/// JavaScript printer state
pub struct JsPrinter {
    /// Output buffer
    output: String,
    /// Current indentation level
    indent: usize,
    /// Indentation string (2 spaces)
    indent_str: &'static str,
    /// Assigned printable names for identifiers.
    ident_names: HashMap<Ident, String>,
    /// Next suffix per mangled base name.
    next_suffix: HashMap<String, usize>,
    /// Module-path resolver used for printing import declarations.
    module_path_resolver: Option<ModulePathResolver>,
}

impl Default for JsPrinter {
    fn default() -> Self {
        Self::new()
    }
}

impl JsPrinter {
    /// Create a new printer
    pub fn new() -> Self {
        Self {
            output: String::new(),
            indent: 0,
            indent_str: "  ",
            ident_names: HashMap::new(),
            next_suffix: HashMap::new(),
            module_path_resolver: None,
        }
    }

    /// Create a new printer with module import resolution context.
    pub fn with_module_path_resolver(module_path_resolver: Option<&ModulePathResolver>) -> Self {
        let mut printer = Self::new();
        printer.module_path_resolver = module_path_resolver.cloned();
        printer
    }

    /// Get the generated JavaScript code
    pub fn into_output(self) -> String {
        self.output
    }

    /// Get a reference to the output
    pub fn output(&self) -> &str {
        &self.output
    }

    /// Write a string
    fn write(&mut self, s: &str) {
        self.output.push_str(s);
    }

    /// Write a character
    fn write_char(&mut self, c: char) {
        self.output.push(c);
    }

    /// Write a newline with current indentation
    fn newline(&mut self) {
        self.output.push('\n');
        for _ in 0..self.indent {
            self.output.push_str(self.indent_str);
        }
    }

    /// Write a space
    fn space(&mut self) {
        self.output.push(' ');
    }

    /// Write a semicolon
    fn semi(&mut self) {
        self.output.push(';');
    }

    /// Increase indentation
    fn indent(&mut self) {
        self.indent += 1;
    }

    /// Decrease indentation
    fn dedent(&mut self) {
        self.indent = self.indent.saturating_sub(1);
    }

    /// Get a unique name for an identifier
    fn ident_name(&mut self, id: &Ident) -> String {
        if id.stamp() == 0 {
            return id.name().to_string();
        }

        if let Some(name) = self.ident_names.get(id) {
            return name.clone();
        }

        let base = convert_ident_name(id.name());
        let next = self.next_suffix.entry(base.clone()).or_insert(0);
        let printed = if *next == 0 {
            base.clone()
        } else {
            format!("{base}${next}")
        };
        *next += 1;
        self.ident_names.insert(id.clone(), printed.clone());
        printed
    }

    /// Print a program
    pub fn print_program(&mut self, program: &Program) {
        self.print_statements(&program.block, true);
    }

    /// Print a module-level program with headers, exports, and purity metadata.
    pub fn print_deps_program(&mut self, program: &DepsProgram) {
        self.print_deps_program_with_directives(program, &[]);
    }

    pub fn print_deps_program_with_directives(
        &mut self,
        program: &DepsProgram,
        directives: &[String],
    ) {
        for directive in directives {
            self.write(directive);
            self.newline();
        }
        self.write("// Generated by ReScript, PLEASE EDIT WITH CARE");
        self.newline();
        if deps_program_is_empty(program) {
            self.write(
                "/* This output is empty. Its source's type definitions, externals and/or unused code got optimized away. */",
            );
            self.newline();
            return;
        }
        self.newline();
        let printed_imports = self.print_module_imports(&program.modules);
        if printed_imports {
            self.newline();
            self.newline();
        } else {
            self.newline();
        }
        self.print_statements(&program.program.block, true);

        if !program.program.exports.is_empty() {
            self.newline();
            self.newline();
            self.print_esmodule_exports(&program.program.exports);
        } else if !program.program.block.is_empty() {
            self.newline();
        }

        self.newline();
        match &program.side_effect {
            None => self.write("/* No side effect */"),
            Some(reason) => {
                let _ = write!(self.output, "/* {} Not a pure module */", reason);
            }
        }
        self.newline();
    }

    fn print_module_imports(&mut self, modules: &[super::ModuleId]) -> bool {
        let mut printed_any = false;

        for module in modules {
            let path = self
                .module_path_resolver
                .as_ref()
                .and_then(|resolver| resolver.resolve_module_path(module));
            let Some(path) = path else {
                continue;
            };

            if printed_any {
                self.newline();
            }

            self.write("import ");
            match &module.kind {
                Kind::External { default: true, .. } => {
                    let name = self.ident_name(&module.id);
                    self.write(&name);
                }
                _ => {
                    self.write("* as ");
                    let name = self.ident_name(&module.id);
                    self.write(&name);
                }
            }
            self.write(" from ");
            self.print_string(&path);

            if let Kind::External {
                import_attributes: Some(import_attributes),
                ..
            } = &module.kind
            {
                self.write(" with ");
                self.write("{type: ");
                self.print_string(&import_attributes.type_);
                self.write("}");
            }

            self.semi();
            printed_any = true;
        }

        printed_any
    }

    /// Print statements
    pub fn print_statements(&mut self, stmts: &Block, top_level: bool) {
        for (i, stmt) in stmts.iter().enumerate() {
            if i > 0 {
                if top_level {
                    self.newline();
                }
                self.newline();
            }
            self.print_statement(stmt, top_level);
        }
    }

    /// Print a statement
    pub fn print_statement(&mut self, stmt: &Statement, top_level: bool) {
        // Print comment if present
        if let Some(ref comment) = stmt.comment {
            self.write("/* ");
            self.write(comment);
            self.write(" */");
            self.newline();
        }

        self.print_statement_desc(&stmt.desc, top_level);
    }

    /// Print a statement description
    fn print_statement_desc(&mut self, desc: &StatementDesc, top_level: bool) {
        match desc {
            StatementDesc::Block(stmts) => {
                if stmts.is_empty() {
                    return;
                }
                self.print_statements(stmts, false);
            }

            StatementDesc::Variable(decl) => {
                if top_level {
                    if let Some(Expression {
                        desc:
                            ExpressionDesc::Fun {
                                is_method: false,
                                params,
                                body,
                                async_,
                                directive,
                                ..
                            },
                        ..
                    }) = &decl.value
                    {
                        self.print_function_declaration(
                            &decl.ident,
                            params,
                            body,
                            *async_,
                            directive.as_deref(),
                        );
                        return;
                    }
                }

                self.print_variable_declaration(decl);
            }

            StatementDesc::Exp(expr) => {
                // Skip pure variable expressions
                if matches!(expr.desc, ExpressionDesc::Var(_)) {
                    return;
                }
                let needs_paren = self.expr_needs_paren(expr);
                if needs_paren {
                    self.write_char('(');
                }
                self.print_expression(expr, 0);
                if needs_paren {
                    self.write_char(')');
                }
                self.semi();
            }

            StatementDesc::If(cond, then_block, else_block) => {
                self.write("if ");
                self.write_char('(');
                self.print_expression(cond, 0);
                self.write(") ");
                self.print_brace_block(then_block);

                if !else_block.is_empty() {
                    self.write(" else ");
                    // Check if else block is just another if
                    if else_block.len() == 1 {
                        if let StatementDesc::If(_, _, _) = &else_block[0].desc {
                            self.print_statement(&else_block[0], false);
                            return;
                        }
                    }
                    self.print_brace_block(else_block);
                }
            }

            StatementDesc::While(cond, body) => {
                self.write("while ");
                self.write_char('(');
                self.print_expression(cond, 0);
                self.write(") ");
                self.print_brace_block(body);
                self.semi();
            }

            StatementDesc::ForRange(init, end, id, direction, body) => {
                let id_name = self.ident_name(id);
                self.write("for ");
                self.write_char('(');

                // Initialization
                if let Some(init_expr) = init {
                    self.write("let ");
                    self.write(&id_name);
                    self.write(" = ");
                    self.print_expression(init_expr, 0);
                }
                self.semi();
                self.space();

                // Condition
                self.write(&id_name);
                match direction {
                    ForDirection::Upto => self.write(" <= "),
                    ForDirection::Downto => self.write(" >= "),
                    ForDirection::Up => self.write(" < "),
                }
                self.print_expression(end, 0);
                self.semi();
                self.space();

                // Increment/decrement
                match direction {
                    ForDirection::Upto | ForDirection::Up => {
                        self.write("++");
                        self.write(&id_name);
                    }
                    ForDirection::Downto => {
                        self.write("--");
                        self.write(&id_name);
                    }
                }

                self.write(") ");
                self.print_brace_block(body);
            }

            StatementDesc::Continue => {
                self.write("continue");
                self.semi();
            }

            StatementDesc::Break => {
                self.write("break");
                self.semi();
            }

            StatementDesc::Return(expr) => {
                // Check for undefined return
                if matches!(expr.desc, ExpressionDesc::Undefined { .. }) {
                    self.write("return");
                    self.semi();
                    return;
                }

                self.write("return ");
                self.print_expression(expr, 0);
                self.semi();
            }

            StatementDesc::IntSwitch(expr, cases, default) => {
                self.write("switch ");
                self.write_char('(');
                self.print_expression(expr, 0);
                self.write(") {");
                self.indent();

                for (value, clause) in cases {
                    self.print_int_case(*value, clause);
                }

                if let Some(default_block) = default {
                    self.newline();
                    self.write("default:");
                    self.indent();
                    self.newline();
                    self.print_statements(default_block, false);
                    self.dedent();
                }

                self.dedent();
                self.newline();
                self.write_char('}');
            }

            StatementDesc::StringSwitch(expr, cases, default) => {
                self.write("switch ");
                self.write_char('(');
                self.print_expression(expr, 0);
                self.write(") {");
                self.indent();

                for clause in cases {
                    self.print_string_case(clause);
                }

                if let Some(default_block) = default {
                    self.newline();
                    self.write("default:");
                    self.indent();
                    self.newline();
                    self.print_statements(default_block, false);
                    self.dedent();
                }

                self.dedent();
                self.newline();
                self.write_char('}');
            }

            StatementDesc::Throw(expr) => {
                self.write("throw ");
                self.print_expression(expr, 0);
                self.semi();
            }

            StatementDesc::Try(body, catch, finally) => {
                self.write("try ");
                self.print_brace_block(body);

                if let Some((exn_id, catch_block)) = catch {
                    let exn_name = self.ident_name(exn_id);
                    self.write(" catch (");
                    self.write(&exn_name);
                    self.write(") ");
                    self.print_brace_block(catch_block);
                }

                if let Some(finally_block) = finally {
                    self.write(" finally ");
                    self.print_brace_block(finally_block);
                }
            }

            StatementDesc::Debugger => {
                self.write("debugger");
                self.semi();
            }
        }
    }

    /// Print a brace-enclosed block
    fn print_brace_block(&mut self, stmts: &Block) {
        self.write_char('{');
        if !stmts.is_empty() {
            self.indent();
            self.newline();
            self.print_statements(stmts, false);
            self.dedent();
            self.newline();
        }
        self.write_char('}');
    }

    /// Print a variable declaration
    fn print_variable_declaration(&mut self, decl: &VariableDeclaration) {
        let var_name = self.ident_name(&decl.ident);
        self.write("let ");
        self.write(&var_name);

        if let Some(value) = &decl.value {
            if !is_undefined_literal(value) {
                self.write(" = ");
                self.print_expression(value, 1);
            }
        }

        self.semi();
    }

    fn with_local_ident_scope<T>(&mut self, f: impl FnOnce(&mut Self) -> T) -> T {
        let saved_names = self.ident_names.clone();
        let saved_suffix = self.next_suffix.clone();
        let out = f(self);
        self.ident_names = saved_names;
        self.next_suffix = saved_suffix;
        out
    }

    fn print_function_declaration(
        &mut self,
        ident: &Ident,
        params: &[Ident],
        body: &Block,
        async_: bool,
        directive: Option<&str>,
    ) {
        if async_ {
            self.write("async ");
        }
        self.write("function ");
        let fn_name = self.ident_name(ident);
        self.write(&fn_name);
        self.with_local_ident_scope(|this| {
            this.write_char('(');
            for (i, param) in params.iter().enumerate() {
                if i > 0 {
                    this.write(", ");
                }
                let param_name = this.ident_name(param);
                this.write(&param_name);
            }
            this.write(") {");
            if !body.is_empty() || directive.is_some() {
                this.indent();
                this.print_function_directive(directive, !body.is_empty());
                this.print_function_body(body);
                this.dedent();
                this.newline();
            }
            this.write_char('}');
        });
    }

    fn print_esmodule_exports(&mut self, exports: &[Ident]) {
        self.write("export {");
        self.indent();
        for export in exports {
            self.newline();
            let local_name = self.ident_name(export);
            self.write(&local_name);
            let export_name = if export.name() == "default" {
                "default".to_string()
            } else {
                convert_ident_name(export.name())
            };
            if local_name != export_name {
                self.write(" as ");
                self.write(&export_name);
            }
            self.write_char(',');
        }
        self.dedent();
        self.newline();
        self.write_char('}');
    }

    fn print_function_directive(&mut self, directive: Option<&str>, body_follows: bool) {
        if let Some(directive) = directive {
            self.newline();
            self.write(directive);
            self.write_char(';');
            if body_follows {
                self.newline();
            }
        } else if body_follows {
            self.newline();
        }
    }

    /// Print an integer case
    fn print_int_case(&mut self, value: i32, clause: &CaseClause) {
        self.newline();
        self.write("case ");
        write!(self.output, "{}", value).unwrap();
        self.write_char(':');

        if !clause.body.is_empty() {
            self.indent();
            self.newline();
            self.print_statements(&clause.body, false);
            if clause.should_break {
                self.newline();
                self.write("break");
                self.semi();
            }
            self.dedent();
        }
    }

    /// Print a string case
    fn print_string_case(&mut self, clause: &StringClause) {
        self.newline();
        self.write("case ");
        self.print_string(&clause.tag_type);
        self.write_char(':');

        if !clause.clause.body.is_empty() {
            self.indent();
            self.newline();
            self.print_statements(&clause.clause.body, false);
            if clause.clause.should_break {
                self.newline();
                self.write("break");
                self.semi();
            }
            self.dedent();
        }
    }

    /// Check if an expression needs parentheses when used as a statement
    fn expr_needs_paren(&self, expr: &Expression) -> bool {
        matches!(
            expr.desc,
            ExpressionDesc::Fun { .. } | ExpressionDesc::Object(_, _)
        )
    }

    /// Print an expression
    pub fn print_expression(&mut self, expr: &Expression, level: u8) {
        // Print comment if present
        if let Some(ref comment) = expr.comment {
            self.write("/* ");
            self.write(comment);
            self.write(" */ ");
        }

        self.print_expression_desc(&expr.desc, level);
    }

    /// Print an expression description
    fn print_expression_desc(&mut self, desc: &ExpressionDesc, level: u8) {
        match desc {
            ExpressionDesc::Null => {
                self.write("null");
            }

            ExpressionDesc::Undefined { .. } => {
                self.write("undefined");
            }

            ExpressionDesc::Var(vident) => {
                self.print_vident(vident);
            }

            ExpressionDesc::Bool(b) => {
                self.write(if *b { "true" } else { "false" });
            }

            ExpressionDesc::Number(n) => {
                self.print_number(n, level);
            }

            ExpressionDesc::Str { delim, txt } => {
                self.print_string_with_delim(txt, *delim);
            }

            ExpressionDesc::Array(elements, _) => {
                self.write_char('[');
                for (i, elem) in elements.iter().enumerate() {
                    if i > 0 {
                        self.write(", ");
                    }
                    self.print_expression(elem, 1);
                }
                self.write_char(']');
            }

            ExpressionDesc::Object(dup, props) => self.print_object_literal(
                level,
                dup.as_deref(),
                props.iter(),
                |this, (name, value)| {
                    this.print_property_name(name);
                    this.write(": ");
                    this.print_expression(value, 1);
                },
            ),

            ExpressionDesc::Seq(e1, e2) => {
                let needs_paren = level > 0;
                if needs_paren {
                    self.write_char('(');
                }
                self.print_expression(e1, 0);
                self.write(", ");
                self.print_expression(e2, 0);
                if needs_paren {
                    self.write_char(')');
                }
            }

            ExpressionDesc::Cond(cond, then_, else_) => {
                let needs_paren = level > 2;
                if needs_paren {
                    self.write_char('(');
                }
                self.print_expression(cond, 3);
                self.write(" ? ");
                self.print_expression(then_, 3);
                self.write(" : ");
                self.print_expression(else_, 3);
                if needs_paren {
                    self.write_char(')');
                }
            }

            ExpressionDesc::Bin(op, left, right) => {
                let (out, lft, rght) = op_precedence(*op);
                let needs_paren = level > out;
                if needs_paren {
                    self.write_char('(');
                }
                self.print_expression(left, lft);
                self.space();
                self.write(op.to_js_string());
                self.space();
                self.print_expression(right, rght);
                if needs_paren {
                    self.write_char(')');
                }
            }

            ExpressionDesc::JsNot(e) => {
                let needs_paren = level > 13;
                if needs_paren {
                    self.write_char('(');
                }
                self.write_char('!');
                self.print_expression(e, 13);
                if needs_paren {
                    self.write_char(')');
                }
            }

            ExpressionDesc::JsBnot(e) => {
                let needs_paren = level > 13;
                if needs_paren {
                    self.write_char('(');
                }
                self.write_char('~');
                self.print_expression(e, 13);
                if needs_paren {
                    self.write_char(')');
                }
            }

            ExpressionDesc::Typeof(e) => {
                self.write("typeof ");
                self.print_expression(e, 13);
            }

            ExpressionDesc::In(prop, obj) => {
                let needs_paren = level > 12;
                if needs_paren {
                    self.write_char('(');
                }
                self.print_expression(prop, 0);
                self.write(" in ");
                self.print_expression(obj, 0);
                if needs_paren {
                    self.write_char(')');
                }
            }

            ExpressionDesc::Call(func, args, _info) => {
                let needs_paren = level > 15;
                if needs_paren {
                    self.write_char('(');
                }

                // Wrap function expressions in parens
                if matches!(func.desc, ExpressionDesc::Fun { .. }) {
                    self.write_char('(');
                    self.print_expression(func, 15);
                    self.write_char(')');
                } else {
                    self.print_expression(func, 15);
                }

                self.write_char('(');
                for (i, arg) in args.iter().enumerate() {
                    if i > 0 {
                        self.write(", ");
                    }
                    self.print_expression(arg, 1);
                }
                self.write_char(')');

                if needs_paren {
                    self.write_char(')');
                }
            }

            ExpressionDesc::FlatCall(func, args) => {
                self.print_expression(func, 15);
                self.write(".apply(null, ");
                self.print_expression(args, 1);
                self.write_char(')');
            }

            ExpressionDesc::New(ctor, args) => {
                let needs_paren = level > 15;
                if needs_paren {
                    self.write_char('(');
                }
                self.write("new ");
                self.print_expression(ctor, 16);
                self.write_char('(');
                if let Some(args) = args {
                    for (i, arg) in args.iter().enumerate() {
                        if i > 0 {
                            self.write(", ");
                        }
                        self.print_expression(arg, 1);
                    }
                }
                self.write_char(')');
                if needs_paren {
                    self.write_char(')');
                }
            }

            ExpressionDesc::ArrayIndex(arr, idx) => {
                let needs_paren = level > 15;
                if needs_paren {
                    self.write_char('(');
                }
                self.print_expression(arr, 15);
                self.write_char('[');
                self.print_expression(idx, 0);
                self.write_char(']');
                if needs_paren {
                    self.write_char(')');
                }
            }

            ExpressionDesc::StringIndex(str_expr, idx) => {
                self.print_expression(str_expr, 15);
                self.write(".codePointAt(");
                self.print_expression(idx, 0);
                self.write_char(')');
            }

            ExpressionDesc::StaticIndex(obj, field, _) => {
                let needs_paren = level > 15;
                if needs_paren {
                    self.write_char('(');
                }
                self.print_expression(obj, 15);
                self.print_property_access(field);
                if needs_paren {
                    self.write_char(')');
                }
            }

            ExpressionDesc::Length(e, obj_type) => {
                let needs_paren = level > 15;
                if needs_paren {
                    self.write_char('(');
                }
                self.print_expression(e, 15);
                self.write(".length");
                if needs_paren {
                    self.write_char(')');
                }
                let _ = obj_type; // Used for type-specific optimizations
            }

            ExpressionDesc::IsNullOrUndefined(e) => {
                let needs_paren = level > 0;
                if needs_paren {
                    self.write_char('(');
                }
                self.print_expression(e, 1);
                self.write(" == null");
                if needs_paren {
                    self.write_char(')');
                }
            }

            ExpressionDesc::StringAppend(e1, e2) => {
                let (out, lft, rght) = op_precedence(BinOp::Plus);
                let needs_paren = level > out;
                if needs_paren {
                    self.write_char('(');
                }
                self.print_expression(e1, lft);
                self.write(" + ");
                self.print_expression(e2, rght);
                if needs_paren {
                    self.write_char(')');
                }
            }

            ExpressionDesc::Fun {
                is_method,
                params,
                body,
                async_,
                directive,
                ..
            } => {
                let use_arrow = !*is_method;
                self.with_local_ident_scope(|this| {
                    // Collect param names upfront to avoid borrow issues
                    let param_names: Vec<String> =
                        params.iter().map(|p| this.ident_name(p)).collect();

                    // Async prefix
                    if *async_ {
                        this.write("async ");
                    }

                    // Function keyword or arrow
                    if !use_arrow {
                        this.write("function");
                    }

                    // Parameters
                    if param_names.len() == 1 && use_arrow {
                        this.write(&param_names[0]);
                    } else {
                        this.write_char('(');
                        for (i, name) in param_names.iter().enumerate() {
                            if i > 0 {
                                this.write(", ");
                            }
                            this.write(name);
                        }
                        this.write_char(')');
                    }

                    this.space();

                    if use_arrow {
                        this.write("=> ");
                    }

                    // Body
                    if use_arrow && directive.is_none() && body.len() == 1 {
                        if let StatementDesc::Return(expr) = &body[0].desc {
                            if !matches!(expr.desc, ExpressionDesc::Undefined { .. }) {
                                let needs_paren = this.expr_needs_paren(expr);
                                if needs_paren {
                                    this.write_char('(');
                                }
                                this.print_expression(expr, 0);
                                if needs_paren {
                                    this.write_char(')');
                                }
                                return;
                            }
                        }
                    }

                    this.write_char('{');
                    if !body.is_empty() || directive.is_some() {
                        this.indent();
                        this.print_function_directive(directive.as_deref(), !body.is_empty());
                        this.print_function_body(body);
                        this.dedent();
                        this.newline();
                    }
                    this.write_char('}');
                });
            }

            ExpressionDesc::RawJsCode(info) => {
                self.print_raw_js(info);
            }

            ExpressionDesc::Await(e) => {
                let needs_paren = level > 13;
                if needs_paren {
                    self.write_char('(');
                }
                self.write("await ");
                self.print_expression(e, 13);
                if needs_paren {
                    self.write_char(')');
                }
            }

            ExpressionDesc::Spread(e) => {
                let needs_paren = level > 13;
                if needs_paren {
                    self.write_char('(');
                }
                self.write("...");
                self.print_expression(e, 13);
                if needs_paren {
                    self.write_char(')');
                }
            }

            ExpressionDesc::TaggedTemplate(tag, strings, values) => {
                self.print_expression(tag, level);
                self.write_char('`');
                for (i, s) in strings.iter().enumerate() {
                    if let ExpressionDesc::Str { txt, .. } = &s.desc {
                        self.write(txt);
                    }
                    if i < values.len() {
                        self.write("${");
                        self.print_expression(&values[i], 0);
                        self.write_char('}');
                    }
                }
                self.write_char('`');
            }

            ExpressionDesc::OptionalBlock(e, identity) => {
                if *identity {
                    self.print_expression(e, level);
                } else {
                    // Would call runtime "some" function
                    self.write("Caml_option.some(");
                    self.print_expression(e, 1);
                    self.write_char(')');
                }
            }

            ExpressionDesc::CamlBlock(elements, _mutable, _tag, tag_info) => {
                use crate::lambda::TagInfo;

                // Check if this is a record with field names
                match tag_info {
                    TagInfo::Record { fields, .. } if fields.len() == elements.len() => {
                        if record_uses_array_syntax(fields) {
                            self.write_char('[');
                            for (i, elem) in elements.iter().enumerate() {
                                if i > 0 {
                                    self.write(", ");
                                }
                                self.print_expression(elem, 1);
                            }
                            self.write_char(']');
                        } else {
                            self.print_object_literal(
                                level,
                                None,
                                elements.iter().zip(fields.iter()).filter_map(
                                    |(elem, (field_name, optional))| {
                                        if *optional && is_undefined_literal(elem) {
                                            None
                                        } else {
                                            Some((field_name.as_str(), elem))
                                        }
                                    },
                                ),
                                |this, (field_name, elem)| {
                                    this.print_literal_property_name(field_name);
                                    this.write(": ");
                                    this.print_expression(elem, 1);
                                },
                            );
                        }
                    }
                    TagInfo::RecordInlined { fields, .. } if fields.len() == elements.len() => {
                        self.print_object_literal(
                            level,
                            None,
                            elements.iter().zip(fields.iter()).filter_map(
                                |(elem, (field_name, optional))| {
                                    if *optional && is_undefined_literal(elem) {
                                        None
                                    } else {
                                        Some((field_name.as_str(), elem))
                                    }
                                },
                            ),
                            |this, (field_name, elem)| {
                                this.print_literal_property_name(field_name);
                                this.write(": ");
                                this.print_expression(elem, 1);
                            },
                        );
                    }
                    TagInfo::RecordExt { fields, .. } if fields.len() == elements.len() => {
                        self.print_object_literal(
                            level,
                            None,
                            elements
                                .iter()
                                .zip(fields.iter())
                                .map(|(elem, field_name)| (field_name.as_str(), elem)),
                            |this, (field_name, elem)| {
                                this.print_literal_property_name(field_name);
                                this.write(": ");
                                this.print_expression(elem, 1);
                            },
                        );
                    }
                    TagInfo::Module(fields) if fields.len() == elements.len() => {
                        self.print_object_literal(
                            level,
                            None,
                            elements.iter().zip(fields.iter()),
                            |this, (elem, field_name)| {
                                let field_name = convert_ident_name(field_name);
                                this.print_literal_property_name(&field_name);
                                this.write(": ");
                                this.print_expression(elem, 1);
                            },
                        );
                    }
                    TagInfo::Constructor { name, .. } => {
                        self.write_char('{');
                        if name == "::" {
                            for (i, elem) in elements.iter().enumerate() {
                                if i > 0 {
                                    self.write(", ");
                                }
                                match i {
                                    0 => self.write("hd"),
                                    1 => self.write("tl"),
                                    _ => {
                                        self.write("_");
                                        self.write(&i.to_string());
                                    }
                                }
                                self.write(": ");
                                self.print_expression(elem, 1);
                            }
                        } else {
                            self.write("TAG: ");
                            self.print_string(name);
                            for (i, elem) in elements.iter().enumerate() {
                                self.write(", _");
                                self.write(&i.to_string());
                                self.write(": ");
                                self.print_expression(elem, 1);
                            }
                        }
                        self.write_char('}');
                    }
                    TagInfo::PolyVar(name) => {
                        // Output as JS object with NAME field: {NAME: "name", VAL: val}
                        self.write_char('{');
                        self.write("NAME: ");
                        self.print_string(name);
                        if let Some(val) = elements.get(1) {
                            // First element is the NAME constant, second is the value
                            self.write(", VAL: ");
                            self.print_expression(val, 1);
                        }
                        self.write_char('}');
                    }
                    _ => {
                        // Output as array for tuples, etc.
                        self.write_char('[');
                        for (i, elem) in elements.iter().enumerate() {
                            if i > 0 {
                                self.write(", ");
                            }
                            self.print_expression(elem, 1);
                        }
                        self.write_char(']');
                    }
                }
            }

            ExpressionDesc::CamlBlockTag(e, tag) => {
                self.print_expression(e, 15);
                self.write_char('.');
                self.write(tag);
            }
        }
    }

    /// Print a variable identifier
    fn print_vident(&mut self, vident: &VIdent) {
        match vident {
            VIdent::Id(id) => {
                let name = self.ident_name(id);
                self.write(&name);
            }
            VIdent::Qualified(module, member) => {
                let mod_name = self.ident_name(&module.id);
                self.write(&mod_name);
                if let Some(m) = member {
                    self.write_char('.');
                    self.write(m);
                }
            }
        }
    }

    fn print_object_literal<T, I, F>(
        &mut self,
        level: u8,
        dup: Option<&Expression>,
        props: I,
        mut print_prop: F,
    ) where
        I: IntoIterator<Item = T>,
        F: FnMut(&mut Self, T),
    {
        let needs_paren = level > 1;
        if needs_paren {
            self.write_char('(');
        }

        self.write_char('{');
        let mut props = props.into_iter().peekable();
        if dup.is_some() || props.peek().is_some() {
            self.indent();

            if let Some(spread) = dup {
                self.newline();
                self.write("...");
                self.print_expression(spread, 1);
                if props.peek().is_some() {
                    self.write_char(',');
                }
            }

            while let Some(prop) = props.next() {
                self.newline();
                print_prop(self, prop);
                if props.peek().is_some() {
                    self.write_char(',');
                }
            }

            self.dedent();
            self.newline();
        }
        self.write_char('}');

        if needs_paren {
            self.write_char(')');
        }
    }

    fn print_literal_property_name(&mut self, name: &str) {
        if is_valid_js_ident(name) {
            self.write(name);
        } else {
            self.print_string(name);
        }
    }

    /// Print a property name
    fn print_property_name(&mut self, name: &PropertyName) {
        match name {
            PropertyName::Lit(s) => self.print_literal_property_name(s),
            PropertyName::Symbol => {
                self.write("[Symbol.for(\"name\")]");
            }
        }
    }

    /// Print property access
    fn print_property_access(&mut self, name: &str) {
        if property_access_uses_dot(name) {
            self.write_char('.');
            self.write(name);
        } else {
            self.write_char('[');
            match name.parse::<i64>() {
                Ok(index) if index.to_string() == name => self.write(name),
                _ => self.print_string(name),
            }
            self.write_char(']');
        }
    }

    /// Print a number
    fn print_number(&mut self, n: &Number, level: u8) {
        let s = match n {
            Number::Float(f) => f.f.clone(),
            Number::Int { i, c: Some(c) } => {
                format!("/* {} */{}", char::from_u32(*c as u32).unwrap_or('?'), i)
            }
            Number::Int { i, c: None } => format!("{}", i),
            Number::BigInt(b) => {
                format!("{}{}n", if b.positive { "" } else { "-" }, b.value)
            }
        };

        // Negative numbers may need parens
        let needs_paren = (s.starts_with('-') && level > 13)
            || (level == 15 && !s.starts_with('I') && !s.starts_with('N'));

        if needs_paren {
            self.write_char('(');
        }
        self.write(&s);
        if needs_paren {
            self.write_char(')');
        }
    }

    /// Print a string literal
    fn print_string(&mut self, s: &str) {
        self.write_char('"');
        for c in s.chars() {
            match c {
                '"' => self.write("\\\""),
                '\\' => self.write("\\\\"),
                '\n' => self.write("\\n"),
                '\r' => self.write("\\r"),
                '\t' => self.write("\\t"),
                c if c < ' ' => {
                    write!(self.output, "\\x{:02x}", c as u32).unwrap();
                }
                c => self.write_char(c),
            }
        }
        self.write_char('"');
    }

    /// Print a string with specific delimiter
    fn print_string_with_delim(&mut self, s: &str, delim: Delim) {
        match delim {
            Delim::None => self.print_string(s),
            Delim::NoQuotes => self.write(s),
            Delim::BackQuotes => {
                self.write_char('`');
                self.write(s);
                self.write_char('`');
            }
            Delim::StarJ => {
                self.write_char('"');
                self.write(s);
                self.write_char('"');
            }
        }
    }

    /// Print raw JavaScript code
    fn print_raw_js(&mut self, info: &JsRawInfo) {
        if info.is_stmt {
            self.newline();
            self.write(&info.code);
            self.newline();
        } else {
            self.write_char('(');
            self.write(&info.code);
            self.write_char(')');
        }
    }

    /// Print a function body (handles trailing return undefined)
    fn print_function_body(&mut self, stmts: &Block) {
        if stmts.is_empty() {
            return;
        }

        let body = if matches!(
            stmts.last().map(|stmt| &stmt.desc),
            Some(StatementDesc::Return(Expression {
                desc: ExpressionDesc::Undefined { .. },
                ..
            }))
        ) {
            &stmts[..stmts.len() - 1]
        } else {
            &stmts[..]
        };

        for (i, stmt) in body.iter().enumerate() {
            if i > 0 {
                self.newline();
            }

            self.print_statement(stmt, false);
        }
    }
}

fn deps_program_is_empty(program: &DepsProgram) -> bool {
    program.modules.is_empty()
        && program.side_effect.is_none()
        && program.program.block.is_empty()
        && program.program.exports.is_empty()
}

fn is_undefined_literal(expr: &Expression) -> bool {
    matches!(expr.desc, ExpressionDesc::Undefined { .. })
}

fn record_uses_array_syntax(fields: &[(String, bool)]) -> bool {
    !fields.is_empty()
        && fields
            .iter()
            .enumerate()
            .all(|(i, (field_name, _))| field_name == &i.to_string())
}

fn convert_ident_name(name: &str) -> String {
    if is_js_keyword_or_global(name) {
        format!("$${name}")
    } else {
        mangle_ident_name(name)
    }
}

fn mangle_ident_name(name: &str) -> String {
    if name
        .chars()
        .all(|c| c.is_ascii_alphanumeric() || matches!(c, '_' | '$'))
    {
        return name.to_string();
    }

    let mut out = String::with_capacity(name.len());
    for (idx, c) in name.chars().enumerate() {
        if c.is_ascii_alphanumeric() || matches!(c, '_' | '$') {
            out.push(c);
        } else {
            out.push_str(mangle_ident_char(c, idx == 0));
        }
    }
    out
}

fn mangle_ident_char(c: char, op: bool) -> &'static str {
    match c {
        '*' => "$star",
        '\'' => "$p",
        '!' => "$bang",
        '>' => "$great",
        '<' => "$less",
        '=' => "$eq",
        '+' => "$plus",
        '-' => {
            if op {
                "$neg"
            } else {
                "$"
            }
        }
        '@' => "$at",
        '^' => "$caret",
        '/' => "$slash",
        '|' => "$pipe",
        '.' => "$dot",
        '%' => "$percent",
        '~' => "$tilde",
        '#' => "$hash",
        ':' => "$colon",
        '?' => "$question",
        '&' => "$amp",
        '(' => "$lpar",
        ')' => "$rpar",
        '{' | '}' => "$lbrace",
        '[' => "$lbrack",
        ']' => "$rbrack",
        _ => "$unknown",
    }
}

/// Get operator precedence (output_level, left_level, right_level)
fn op_precedence(op: BinOp) -> (u8, u8, u8) {
    match op {
        BinOp::Eq => (1, 14, 1),
        BinOp::Or => (3, 3, 4),
        BinOp::And => (4, 4, 5),
        BinOp::Bor => (6, 6, 7),
        BinOp::Bxor => (7, 7, 8),
        BinOp::Band => (8, 8, 9),
        BinOp::EqEqEq | BinOp::NotEqEq => (9, 9, 10),
        BinOp::Lt | BinOp::Le | BinOp::Gt | BinOp::Ge | BinOp::InstanceOf => (10, 10, 11),
        BinOp::Lsl | BinOp::Lsr | BinOp::Asr => (11, 11, 12),
        BinOp::Plus | BinOp::Minus => (12, 12, 13),
        BinOp::Mul | BinOp::Div | BinOp::Mod => (13, 13, 14),
        BinOp::Pow => (14, 15, 14), // Right-associative
        BinOp::Bnot => (14, 14, 14),
    }
}

/// Check if a string is a valid JavaScript identifier
fn is_valid_js_ident(s: &str) -> bool {
    if s.is_empty() {
        return false;
    }

    let mut chars = s.chars();
    match chars.next() {
        Some(c) if c.is_ascii_alphabetic() || c == '_' || c == '$' => {}
        _ => return false,
    }

    for c in chars {
        if !c.is_ascii_alphanumeric() && c != '_' && c != '$' {
            return false;
        }
    }

    !is_reserved_word(s)
}

fn property_access_uses_dot(s: &str) -> bool {
    if s.is_empty() {
        return false;
    }

    let mut chars = s.chars();
    match chars.next() {
        Some(c) if c.is_ascii_alphabetic() || c == '_' || c == '$' => {}
        _ => return false,
    }

    chars.all(|c| c.is_ascii_alphanumeric() || c == '_' || c == '$')
}

