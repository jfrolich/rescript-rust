//! Program-level JavaScript printer - prints top-level program structure.
//!
//! This module handles printing the overall file structure: the header comment,
//! import declarations, export blocks, purity metadata, and the module wrapper.
//! This corresponds to OCaml's `js_dump_program.ml`.

use super::op::Kind;
use super::printer::{JsPrinter, js_export_name};
use super::source_map::{SourceMapBuilder, SourceMapMode, inline_comment, linked_comment};
use super::{
    Block, DepsProgram, Expression, ExpressionDesc, ModuleFormat, ModulePathResolver, Program,
    Statement, StatementDesc,
};
use crate::binary_ast::ppx::{JsStmtClassification, classify_js_stmt};
use crate::ident::Ident;
use crate::intern::StrIdx;
use std::collections::HashMap;
use std::path::Path;
use std::sync::Arc;

impl JsPrinter<'_> {
    /// Print a program
    pub fn print_program(&mut self, program: &Program) {
        self.reserve_js_names(&program.block);
        self.at_least_two_lines();
        self.print_statements(&program.block, true);
    }

    /// Print a module-level program with headers, exports, and purity metadata.
    pub fn print_deps_program(&mut self, program: &DepsProgram) {
        self.print_deps_program_with_directives(program, &[]);
    }

    pub fn print_deps_program_with_directives(
        &mut self,
        program: &DepsProgram,
        directives: &[String],
    ) {
        self.print_deps_program_with_directives_and_options(program, directives, true);
    }

    pub fn print_deps_program_with_directives_and_options(
        &mut self,
        program: &DepsProgram,
        directives: &[String],
        emit_header: bool,
    ) {
        for directive in directives {
            self.write(directive);
            self.newline();
        }
        if emit_header {
            self.write("// Generated by ReScript, PLEASE EDIT WITH CARE");
            self.newline();
        }
        // OCaml checks for an empty dependency program before dispatching to
        // CommonJS/ESM printers, so empty CommonJS output does not receive the
        // strict directive; see compiler/core/js_dump_program.ml:121-123 and
        // compiler/core/js_dump_program.ml:73-88.
        if deps_program_is_empty(program) {
            self.write(
                "/* This output is empty. Its source's type definitions, externals and/or unused code got optimized away. */",
            );
            self.newline();
            return;
        }
        if self.current_module_format() == ModuleFormat::CommonJs {
            self.write("'use strict';");
            self.newline();
        }
        let (file_comments, block_start) = split_leading_file_comments(&program.program.block);
        if file_comments.is_empty() {
            self.at_least_two_lines();
        } else {
            for comment in file_comments {
                self.write_decoded_internal_string(comment);
                self.newline();
            }
            self.at_least_two_lines();
        }
        self.reserve_js_names(&program.program.block);
        let _printed_imports = self.print_module_imports(&program.modules);
        self.at_least_two_lines();
        self.reserve_idents_in_current_scope(&program.program.name_reservations);
        self.print_statements(&program.program.block[block_start..], true);

        self.at_least_two_lines();
        if !program.program.exports.is_empty() {
            match self.current_module_format() {
                ModuleFormat::EsModule => self.print_esmodule_exports(&program.program.exports),
                ModuleFormat::CommonJs => self.print_commonjs_exports(&program.program.exports),
            }
        }

        self.newline();
        match &program.side_effect {
            None => self.write("/* No side effect */"),
            Some(reason) => {
                self.write(&format!("/* {} Not a pure module */", reason));
            }
        }
        self.newline();
    }

    fn current_module_format(&self) -> ModuleFormat {
        self.module_path_resolver
            .map(ModulePathResolver::module_format)
            .unwrap_or(ModuleFormat::EsModule)
    }

    pub(super) fn print_module_imports(&mut self, modules: &[super::ModuleId]) -> bool {
        let mut printed_any = false;

        for module in modules {
            // OCaml keeps dynamic imports in deps for effect calculation but
            // filters them out of static import/require emission; see
            // compiler/core/js_dump_program.ml:76-98.
            if module.dynamic_import {
                continue;
            }

            let path = self
                .module_path_resolver
                .and_then(|resolver| resolver.resolve_module_path(module));
            let Some(path) = path else {
                continue;
            };

            if printed_any {
                self.newline();
            }

            match self.current_module_format() {
                ModuleFormat::EsModule => {
                    self.write("import ");
                    match &module.kind {
                        Kind::External { default: true, .. } => {
                            let name = self.module_ident_name(&module.id);
                            self.write(&name);
                        }
                        _ => {
                            self.write("* as ");
                            let name = self.module_ident_name(&module.id);
                            self.write(&name);
                        }
                    }
                    self.write(" from ");
                    self.print_string(&path);

                    if let Kind::External {
                        import_attributes: Some(import_attributes),
                        ..
                    } = &module.kind
                    {
                        self.write(" with ");
                        self.write("{");
                        for (index, (key, value)) in import_attributes.entries.iter().enumerate() {
                            if index > 0 {
                                self.write(", ");
                            }
                            self.print_string(key);
                            self.write(": ");
                            self.print_string(value);
                        }
                        self.write("}");
                    }
                }
                ModuleFormat::CommonJs => {
                    self.write("let ");
                    let name = self.module_ident_name(&module.id);
                    self.write(&name);
                    self.write(" = require(");
                    self.print_string(&path);
                    self.write_char(')');
                    // OCaml compiler/core/js_dump_import_export.ml:111-120:
                    // CommonJS requires append `.default` from the external's
                    // default flag independently of import attributes.
                    if matches!(&module.kind, Kind::External { default: true, .. }) {
                        self.write(".default");
                    }
                }
            }

            self.semi();
            printed_any = true;
        }

        printed_any
    }

    fn print_esmodule_exports(&mut self, exports: &[Ident]) {
        self.write("export {");
        self.indent();
        for export in exports {
            self.newline();
            let local_name = self.ident_name(export);
            self.write(&local_name);
            let export_name = js_export_name(export.name());
            if local_name != export_name {
                self.write(" as ");
                self.write(&export_name);
            }
            self.write_char(',');
        }
        self.dedent();
        self.newline();
        self.write_char('}');
    }

    fn print_commonjs_exports(&mut self, exports: &[Ident]) {
        for (index, export) in exports.iter().enumerate() {
            if index > 0 {
                self.newline();
            }
            let local_name = self.ident_name(export);
            let export_name = js_export_name(export.name());
            self.write("exports.");
            self.write(&export_name);
            self.write(" = ");
            self.write(&local_name);
            self.semi();
            // OCaml inserts the CommonJS interop marker immediately after a
            // default export; see compiler/core/js_dump_import_export.ml:51-53.
            if export.name() == "default" {
                self.newline();
                self.write("exports.__esModule = true");
                self.semi();
            }
        }
    }
}

fn deps_program_is_empty(program: &DepsProgram) -> bool {
    program.modules.is_empty()
        && program.side_effect.is_none()
        && program.program.block.is_empty()
        && program.program.exports.is_empty()
        && program.program.name_reservations.is_empty()
}

fn split_leading_file_comments(block: &Block) -> (Vec<&str>, usize) {
    let mut index = 0;
    let mut comments = Vec::new();

    while let Some(Statement {
        desc:
            StatementDesc::Exp(Expression {
                desc: ExpressionDesc::RawJsCode(info),
                ..
            }),
        ..
    }) = block.get(index)
    {
        if !info.is_stmt
            || !matches!(
                classify_js_stmt(&info.code),
                JsStmtClassification::JsStmtComment
            )
        {
            break;
        }
        comments.push(info.code.as_str());
        index += 1;
    }

    (comments, index)
}

/// Print a program to a string
pub fn print_program(program: &Program) -> String {
    let mut printer = JsPrinter::with_capacity(estimated_block_output_capacity(
        program.block.len(),
        program.exports.len(),
        0,
        0,
        true,
    ));
    printer.print_program(program);
    printer.into_output()
}

fn estimated_block_output_capacity(
    statement_count: usize,
    export_count: usize,
    module_count: usize,
    directive_bytes: usize,
    emit_header: bool,
) -> usize {
    let header_bytes = if emit_header { 128 } else { 0 };
    let estimate = 256usize
        .saturating_add(header_bytes)
        .saturating_add(directive_bytes)
        .saturating_add(statement_count.saturating_mul(384))
        .saturating_add(export_count.saturating_mul(48))
        .saturating_add(module_count.saturating_mul(96));
    estimate.min(4 * 1024 * 1024)
}

fn estimated_deps_program_output_capacity(
    program: &DepsProgram,
    directives: &[String],
    emit_header: bool,
) -> usize {
    let directive_bytes = directives.iter().map(|directive| directive.len() + 1).sum();
    estimated_block_output_capacity(
        program.program.block.len(),
        program.program.exports.len(),
        program.modules.len(),
        directive_bytes,
        emit_header,
    )
}

/// Print a module-level program to a string.
pub fn print_deps_program(
    program: &DepsProgram,
    module_path_resolver: Option<&ModulePathResolver>,
) -> String {
    print_deps_program_with_directives(program, module_path_resolver, &[], false, false)
}

pub fn print_deps_program_with_directives(
    program: &DepsProgram,
    module_path_resolver: Option<&ModulePathResolver>,
    directives: &[String],
    debug: bool,
    jsx_preserve: bool,
) -> String {
    print_deps_program_with_directives_and_options(
        program,
        module_path_resolver,
        directives,
        debug,
        jsx_preserve,
        true,
    )
}

pub fn print_deps_program_with_directives_and_options(
    program: &DepsProgram,
    module_path_resolver: Option<&ModulePathResolver>,
    directives: &[String],
    debug: bool,
    jsx_preserve: bool,
    emit_header: bool,
) -> String {
    let capacity = estimated_deps_program_output_capacity(program, directives, emit_header);
    let mut printer = JsPrinter::with_module_path_resolver_options_and_capacity(
        module_path_resolver,
        debug,
        jsx_preserve,
        capacity,
    );
    printer.print_deps_program_with_directives_and_options(program, directives, emit_header);
    printer.into_output()
}

/// Print one concrete output target and collect mappings from JS IR source
/// locations. This is the Rust counterpart of
/// `Lam_compile_main.dump_deps_program_with_source_map`.
pub fn print_deps_program_with_source_map(
    program: &DepsProgram,
    module_path_resolver: Option<&ModulePathResolver>,
    directives: &[String],
    debug: bool,
    jsx_preserve: bool,
    emit_header: bool,
    target_file: &Path,
    source_file: &Path,
    mode: SourceMapMode,
    sources_content: bool,
    source_root: &str,
    source_file_names: Arc<HashMap<StrIdx, String>>,
) -> (String, Option<String>) {
    let capacity = estimated_deps_program_output_capacity(program, directives, emit_header);
    let mut printer = JsPrinter::with_module_path_resolver_options_and_capacity(
        module_path_resolver,
        debug,
        jsx_preserve,
        capacity,
    );
    printer.set_source_map_builder(
        SourceMapBuilder::new(
            target_file,
            source_file,
            source_root.to_string(),
            sources_content,
        )
        .with_source_file_names(source_file_names),
    );
    printer.print_deps_program_with_directives_and_options(program, directives, emit_header);
    let json = printer
        .take_source_map_builder()
        .expect("source map builder installed")
        .json();
    let mut output = printer.into_output();
    match mode {
        SourceMapMode::Linked => {
            output.push_str(&linked_comment(Path::new(&format!(
                "{}.map",
                target_file.display()
            ))));
            (output, Some(json))
        }
        SourceMapMode::Hidden => (output, Some(json)),
        SourceMapMode::Inline => {
            output.push_str(&inline_comment(&json));
            (output, None)
        }
        SourceMapMode::None => (output, None),
    }
}

