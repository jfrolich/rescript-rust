use std::{
    fs,
    path::Path,
    process::{Command, Output},
};
use tempfile::TempDir;

fn run(args: &[&str], dirs: &[&Path]) -> Output {
    Command::new(env!("CARGO_BIN_EXE_js-reformat"))
        .args(args)
        .args(dirs)
        .output()
        .unwrap()
}
fn pair(a: &str, b: &str) -> (TempDir, TempDir) {
    let a_dir = TempDir::new().unwrap();
    let b_dir = TempDir::new().unwrap();
    fs::write(a_dir.path().join("a.js"), a).unwrap();
    fs::write(b_dir.path().join("a.js"), b).unwrap();
    (a_dir, b_dir)
}
#[test]
fn parentheses_compare_equal() {
    let (a, b) = pair("const x = (((1 + 2)));", "const x = 1 + 2;");
    assert!(run(&["compare"], &[a.path(), b.path()]).status.success());
}
#[test]
fn difference_reports_line() {
    let (a, b) = pair("const x = 1;\nconst y = 2;", "const x = 1;\nconst y = 3;");
    let output = run(&["compare"], &[a.path(), b.path()]);
    assert_eq!(output.status.code(), Some(1));
    let text = String::from_utf8(output.stdout).unwrap();
    assert!(text.contains("a.js:2"), "{text}");
    assert!(
        text.contains("const y = 2;") && text.contains("const y = 3;"),
        "{text}"
    );
}
#[test]
fn syntax_errors_exit_two_in_all_commands() {
    let (a, b) = pair("const = ;", "const x = 1;");
    for command in ["compare", "format"] {
        assert_eq!(
            run(&[command], &[a.path(), b.path()]).status.code(),
            Some(2)
        );
    }
    assert_eq!(run(&["check"], &[a.path()]).status.code(), Some(2));
}
#[test]
fn jsx_and_samples_are_fixed_points() {
    let dir = TempDir::new().unwrap();
    for (name, source) in [
        (
            "a.jsx",
            "export const x = <div title='hello'>{1 + 2}</div>;",
        ),
        ("b.mjs", "export const f = (x) => ({value: ((x ?? 1))});"),
        (
            "c.cjs",
            "const r = /a+/g; if (r.test('aa')) console.log(`ok`);",
        ),
        ("d.js", "const x = (1 + 2) * 3; // note\n"),
    ] {
        fs::write(dir.path().join(name), source).unwrap();
    }
    let output = run(&["check"], &[dir.path()]);
    assert!(output.status.success(), "{output:?}");
    assert!(
        String::from_utf8(output.stdout)
            .unwrap()
            .contains("4 files, 0 failed, 0 not a fixed point")
    );
}
#[test]
fn comments_and_preformatted_candidate() {
    let source =
        "// Generated by ReScript, PLEASE EDIT WITH CARE\nconst x = 1;\n/* No side effect */\n";
    let (a, b) = pair(source, "");
    assert!(run(&["format"], &[a.path(), b.path()]).status.success());
    assert_eq!(fs::read_to_string(b.path().join("a.js")).unwrap(), source);
    assert!(
        run(&["compare", "--candidate-formatted"], &[a.path(), b.path()])
            .status
            .success()
    );
    assert!(
        run(&["check", "--strip-comments"], &[a.path()])
            .status
            .success()
    );
    assert!(
        run(&["format", "--strip-comments"], &[a.path(), b.path()])
            .status
            .success()
    );
    assert_eq!(
        fs::read_to_string(b.path().join("a.js")).unwrap(),
        "const x = 1;\n"
    );
    assert!(
        run(&["compare", "--strip-comments"], &[a.path(), b.path()])
            .status
            .success()
    );
    assert!(
        run(
            &["compare", "--strip-comments", "--candidate-formatted"],
            &[a.path(), b.path()]
        )
        .status
        .success()
    );
}
#[test]
fn union_is_sorted_and_other_files_are_ignored() {
    let (a, b) = pair("", "");
    fs::create_dir(a.path().join("nested")).unwrap();
    fs::write(a.path().join("nested/z.jsx"), "const z = <Z/>;").unwrap();
    fs::write(b.path().join("b.mjs"), "const b = 1;").unwrap();
    fs::write(a.path().join("ignored.txt"), "invalid JavaScript").unwrap();
    let output = run(&["compare"], &[a.path(), b.path()]);
    assert_eq!(output.status.code(), Some(1));
    let text = String::from_utf8(output.stdout).unwrap();
    assert!(
        text.find("b.mjs:1 (missing reference)").unwrap()
            < text.find("nested/z.jsx:1 (missing candidate)").unwrap()
    );
    assert!(text.contains("3 files, 2 different or missing, 0 failed"));
    assert!(run(&["format"], &[a.path(), b.path()]).status.success());
    assert!(b.path().join("nested/z.jsx").is_file());
    assert!(!b.path().join("ignored.txt").exists());
}
#[test]
fn preformatted_candidate_is_compared_as_exact_bytes() {
    let (a, b) = pair("const x = 1;", "const x = 1;");
    let output = run(&["compare", "--candidate-formatted"], &[a.path(), b.path()]);
    assert_eq!(output.status.code(), Some(1));
    assert!(String::from_utf8(output.stdout).unwrap().contains("a.js:1"));
}
