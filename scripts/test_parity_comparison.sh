#!/usr/bin/env bash
# Regression tests for the shared JS comparison, independent of the compilers.
set -euo pipefail
PROJECT_ROOT=$(cd "$(dirname "$0")/.."; pwd -P)
RUST_TARGET=debug
source "$PROJECT_ROOT/scripts/parity_lib.sh"
PARITY_COMPARE_MODE=reformat
parity_init_comparison
work=$(mktemp -d)
trap 'find "$work" -type f -delete; find "$work" -depth -type d -empty -delete' EXIT
reference="$work/reference.mjs"
candidate="$work/candidate.mjs"
expect() {
    local expected="$1" mode="$2" status=0
    PARITY_COMPARE_MODE="$mode" parity_compare_js "$reference" "$candidate" > "$work/result" 2>&1 || status=$?
    if [[ "$status" != "$expected" ]]; then
        cat "$work/result"
        echo "Expected $expected, got $status ($mode)" >&2
        exit 1
    fi
    echo "$label: $mode status=$status"
}
printf 'const x = 1;\n' > "$reference"
printf 'const x=1;\n' > "$candidate"
label=formatting-only
expect 1 exact
expect 0 reformat
printf 'const x=2;\n' > "$candidate"
label=one-token
expect 1 exact
expect 1 reformat
printf 'const x = ;\n' > "$candidate"
label=parse-error
expect 2 reformat
grep -F "$candidate" "$work/result" > /dev/null
# Identical invalid text must still be parsed, not short-circuited by cmp.
cp "$candidate" "$reference"
expect 2 reformat
printf '// Generated by ReScript, PLEASE EDIT WITH CARE\nconst x=1;\n/* No side effect */\n' > "$reference"
printf '// Generated by ReScript, PLEASE EDIT WITH CARE\nconst x=1;\n/* Not a pure module */\n' > "$candidate"
label=trailer
expect 1 reformat
printf 'const x=/* constructor */1;\n' > "$reference"
printf 'const x=1;\n' > "$candidate"
label=decoration
expect 0 reformat
