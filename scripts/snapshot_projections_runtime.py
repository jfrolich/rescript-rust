#!/usr/bin/env python3
"""Exercise saved fresh compiler stdout, without recompiling or normalizing it."""
import json
from pathlib import Path
import subprocess
D = Path('/tmp/rescript-snapshot-projections-experiment')
rows = []
checks = {
    'SnapshotProjections': 'assert.equal(m.integer,6); assert.equal(m.text,"first"); assert.equal(m.completed,5); assert.equal(m.result,8); assert.equal(m.partial(9,10),9); assert.equal(m.inferred((x,y)=>x+y,7),14); assert.equal(m.viaAlias(m.choose),8);',
    'TypeArgStorage': 'assert.equal(m.integer,7); assert.equal(m.text,"first"); assert.equal(m.nested,7); assert.equal(m.select(1,2,3),1); assert.equal(m.curried(4,5)(6),4); assert.equal(m.project({generic:(x,y,z)=>x}),"a");',
}
for fixture, assertions in checks.items():
    for variant in ['ocaml', 'rust', 'control']:
        path = D / f'fixtures/{fixture}-js-{variant}.js'
        assert path.read_bytes().startswith(b'// Generated by ReScript')
        code = f'const assert=require("node:assert/strict"); const m=require({json.dumps(str(path))}); {assertions}'
        proc = subprocess.run(['node','-e',code], capture_output=True, timeout=10)
        (D / f'logs/runtime-{fixture}-{variant}.log').write_bytes(proc.stdout + proc.stderr)
        rows.append(dict(fixture=fixture, variant=variant, exit=proc.returncode))
(D / 'runtime-results.json').write_text(json.dumps(rows, indent=2))
assert all(r['exit'] == 0 for r in rows)
