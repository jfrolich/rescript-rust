#!/usr/bin/env python3
"""Short exact D/probe fixture checks; never compile the Tella corpus here."""
import hashlib,json,os,subprocess
from pathlib import Path
R=Path('/Users/jake/checkouts/rescript-rust');D=Path('/Users/jake/.opensession/artifacts/rescript-performance-20260905/env-ownership');assert Path.cwd()==R
F=D/'fixtures-3';F.mkdir(exist_ok=True)
source='''module First = {
  type t = {value: int}
  type rec chain = End | Next(int, chain)
  let identity = (x: t) => x
}
module Alias = First
module Captured = {
  module Before = Alias
  module Alias = {type t = {value: string}}
  let old: Before.t = {value: 7}
  let fresh: Alias.t = {value: "seven"}
}
let a: First.t = {value: 3}
let b: Alias.t = Alias.identity(a)
let tree: First.chain = Next(4, End)
let result = (a.value, b.value, Captured.old.value, Captured.fresh.value, tree)
'''
p=F/'Layout__Types.res';p.write_text(source)
controls=D.parent/'type-arg/bin';probe=D/'probe-source/rewatch/target/release'
results=[]
for mode in ['js','-dtyped-sexp','-drawlambda']:
 out={}
 for v,exe in [('D',controls/'bsc-D'),('P',probe/'bsc')]:
  args=[str(exe),'-nopervasives','-nostdlib']+([] if mode=='js' else [mode])+[str(p)]
  cp=subprocess.run(args,cwd=F,capture_output=True,timeout=10)
  prefix=F/f'standalone-{v}-{mode}'
  prefix.with_suffix('.stdout').write_bytes(cp.stdout);prefix.with_suffix('.stderr').write_bytes(cp.stderr)
  # Probe records are kept verbatim in raw logs. This extraction is diagnostic
  # framing, not normalization of the compiler's typedtree/lambda payload.
  stderr=b'\n'.join(line for line in cp.stderr.split(b'\n') if not line.startswith((b'[env-roots]',b'[env-ownership]',b'[env-probe-cleanup]',b'[env-teardown]')))
  out[v]=(cp.returncode,cp.stdout,stderr)
 row={'mode':mode,'equal':out['D']==out['P'],'exits':{v:x[0] for v,x in out.items()},'stdout_bytes':{v:len(x[1]) for v,x in out.items()}}
 results.append(row);print(row,flush=True)
 (F/'standalone-results.json').write_text(json.dumps(results,indent=2))
 assert row['equal'] and all(x[0]==0 for x in out.values())
 if mode=='js':assert all(x[1].startswith(b'// Generated by ReScript') and len(x[1])>50 for x in out.values())
# Same small project path across variants, selected clean outside each build.
project=F/'project';(project/'src').mkdir(parents=True,exist_ok=True)
(project/'src/Layout__Types.res').write_text(source)
(project/'rescript.json').write_text(json.dumps({'name':'env-ownership-fixture','sources':['src'],'package-specs':{'module':'esmodule','in-source':True}}))
(project/'package.json').write_text(json.dumps({'name':'env-ownership-fixture','version':'0.0.0'}))
outputs={}
for v,exe in [('D',controls/'rescript-D'),('P',probe/'rescript')]:
 e=os.environ.copy()
 for k in list(e):
  if k.startswith(('RESCRIPT_','OTEL_','MIMALLOC_')):del e[k]
 e.update(RESCRIPT_RUNTIME=str(R/'packages/@rescript/runtime'),RESCRIPT_BSC_EXE=str(controls/'bsc-D'),RAYON_NUM_THREADS='1',RESCRIPT_MODULE_TIMINGS='1')
 clean=subprocess.run([str(exe),'clean',str(project)],env=e,capture_output=True,timeout=10)
 (F/f'project-{v}-clean.log').write_bytes(clean.stdout+clean.stderr);assert clean.returncode==0
 run=subprocess.run([str(exe),'build','--in-process','--no-timing','true',str(project)],env=e,capture_output=True,timeout=10)
 (F/f'project-{v}.log').write_bytes(run.stdout+run.stderr);assert run.returncode==0,(v,run.stderr.decode()[-2000:])
 js=project/'src/Layout__Types.res.js'
 if not js.exists():js=project/'src/Layout__Types.js'
 outputs[v]=js.read_bytes();assert outputs[v]
 if v=='P':
  records=[json.loads(line.split(b'] ',1)[1]) for line in run.stderr.splitlines() if line.startswith(b'[env-ownership] ')]
  layout=[x for x in records if x['module']=='Layout__Types'];assert len(layout)==1
  for x in records:
   c=x['stats'];assert c.get('query_requests',0)==x['unique_query_keys']+c.get('query_repeat_key',0)
   assert c.get('component_requests',0)==x['unique_component_keys']+c.get('component_repeat_key',0)
   times=x['times'];assert all(0<=ex<=inc for n,inc,ex in times.values())
   assert sum(t[2] for k,t in times.items() if k!='outer_union')==times.get('outer_union',[0,0,0])[1]
  assert b'[module-timing] module=Layout__Types ' in run.stderr
  (F/'layout-record.json').write_text(json.dumps(layout[0],indent=2))
assert outputs['D']==outputs['P'];(F/'project-result.json').write_text(json.dumps({'equal_js':True,'bytes':len(outputs['D'])}))
print('All standalone/project checks passed; Layout__Types module and phase records present.')
