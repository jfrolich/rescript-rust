#!/usr/bin/env python3
"""Exact native/D/candidate fixture output, including fresh standalone JS stdout."""
import json,os,shutil
from pathlib import Path
from env_ownership_runner import bounded
R=Path('/Users/jake/checkouts/rescript-rust');assert Path.cwd()==R
D=Path('/Users/jake/.opensession/artifacts/rescript-performance-20260905/env-ownership/candidate/fixtures');assert not D.exists();D.mkdir()
compilers={'ocaml':R/'_build/install/default/bin/bsc','D':D.parents[2]/'type-arg/bin/bsc-D','candidate':R/'compiler-rust/target/release/bsc'}
# Durable controls live beside env-ownership, not inside its candidate directory.
compilers['D']=Path('/Users/jake/.opensession/artifacts/rescript-performance-20260905/type-arg/bin/bsc-D')
rows=[]
for source in [R/'projects/in-process-performance/env-ownership-fixtures/EnvOwnership.res',R/'projects/in-process-performance/type-arg-fixtures/TypeArgStorage.res']:
 dest=D/source.name;shutil.copy2(source,dest)
 for mode in ['-dparsetree','-dtyped-sexp','-drawlambda','-dlambda-sexp','js']:
  out={}
  for variant,exe in compilers.items():
   args=[str(exe),'-I',str(R/'packages/@rescript/runtime/lib/ocaml')]+([] if mode=='js' else [mode])+[str(dest)]
   row,payload=bounded(args,os.environ.copy(),D/f'{source.stem}-{mode}-{variant}',10)
   stdout=(D/f'{source.stem}-{mode}-{variant}.stdout').read_bytes();stderr=(D/f'{source.stem}-{mode}-{variant}.stderr').read_bytes()
   out[variant]=(row['exit'],stdout,stderr)
   assert row['exit']==0 and not row['timeout'],(source.name,mode,variant)
   if mode=='js':assert stdout.startswith(b'// Generated by ReScript') and len(stdout)>50
  result={'fixture':source.name,'mode':mode,'native_equal':out['ocaml']==out['candidate'],'D_equal':out['D']==out['candidate'],'stdout_bytes':{v:len(x[1]) for v,x in out.items()}}
  rows.append(result);(D/'results.json').write_text(json.dumps(rows,indent=2));print(result,flush=True)
assert all(r['D_equal'] for r in rows),'New D/candidate difference; preserved'
assert all(r['native_equal'] for r in rows),'Native differences retained; no normalization'
